// tools/gen-registry.js
//
// Regenerates src/features/loader.lua.
//
// The OSS release shipped loader.lua as a one-line stub, so aztup.features is
// empty and every toggle in src/utility/ui/wrapper.lua bails at line 323:
//
//     local feature = aztup.features[ID];
//     if not feature then return end;
//
// This walks src/features for modules, harvests the toggle ids out of
// src/ui/tabs/*.lua, and emits a static id -> module map plus the Feature
// global the rest of the tree expects.
//
//   node tools/gen-registry.js

const fs = require("fs");
const path = require("path");

const ROOT = "C:/Deepwoken cheat/project-rain-oss-master";
const FEATURES = path.join(ROOT, "src", "features");
const TABS = path.join(ROOT, "src", "ui", "tabs");

const argv = process.argv.slice(2);

function walk(dir, out = []) {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, e.name);
        if (e.isDirectory()) walk(full, out);
        else out.push(full);
    }
    return out;
}

const SKIP = new Set(["loader.lua", "generic_feature.lua"]);

// basename -> "@src/features/..." module id
const byBasename = new Map();
const allModules = [];

for (const file of walk(FEATURES)) {
    if (!file.endsWith(".lua")) continue;
    const rel = path.relative(ROOT, file).split(path.sep).join("/");
    const base = path.basename(file, ".lua");
    if (SKIP.has(path.basename(file))) continue;

    allModules.push(rel);
    // Bundle manifest keys are extensionless, so emit it the same way.
    if (!byBasename.has(base)) byBasename.set(base, "@" + rel.replace(/\.lua$/, ""));
}

// Dashes and underscores are interchangeable: the UI calls the toggle
// "auto_parry" but the module is src/features/auto-parry/auto-parry.lua.
const norm = (s) => s.toLowerCase().replace(/[_-]/g, "");

const byNorm = new Map();
for (const [base, mod] of byBasename) {
    if (!byNorm.has(norm(base))) byNorm.set(norm(base), mod);
}

// ── harvest ids from the UI ────────────────────────────────────────────────
const ids = new Map(); // id -> source file

// Every wrapper method whose first argument is the element id. Missing one
// means the toggle exists in the UI but has no module behind it — which is how
// auto_parry stayed unwired: it uses newToggleWithKeybind, not newToggle.
const ID_FIRST_CONSTRUCTORS = [
    "newToggle",
    "newToggleWithKeybind",
    "newRiskyToggle",
    "newRiskyToggleWithKeybind",
    "newSlider",
    "newMinMaxSlider",
    "newDropdown",
    "newTextbox",
    "newKeybind",
    "newDependencyBox",
    "newKeyPicker",
];

const patterns = [
    /\{\s*"([a-z0-9_-]+)"\s*,/g,   // newToggleGroup tuples
    ...ID_FIRST_CONSTRUCTORS.map((n) => new RegExp(n + '\\(\\s*"([a-z0-9_-]+)"', "g")),
];

for (const file of walk(TABS)) {
    if (!file.endsWith(".lua")) continue;
    const src = fs.readFileSync(file, "utf8");
    const name = path.basename(file);
    for (const re of patterns) {
        let m;
        while ((m = re.exec(src)) !== null) {
            if (!ids.has(m[1])) ids.set(m[1], name);
        }
    }
}

// ── resolve ────────────────────────────────────────────────────────────────
const resolved = [];
const unresolved = [];

for (const [id, from] of [...ids].sort((a, b) => a[0].localeCompare(b[0]))) {
    const mod = byBasename.get(id) || byNorm.get(norm(id));
    if (mod) resolved.push({ id, mod, from });
    else unresolved.push({ id, from });
}

// ── preserve hand-written content ──────────────────────────────────────────
// This file is generated, and has been hand-edited twice. Two protections:
//
//   1. anything between the HAND-WRITTEN markers carries across verbatim
//   2. if loader.lua on disk does not carry the generator sentinel, it was
//      written by hand and we refuse to clobber it without --force
//
// Without (2) a hand-written loader is destroyed silently and the symptom is
// invisible: aztup.features loses entries, wrapper.lua:323 gets nil, and every
// affected toggle just stops doing anything.

const LOADER_PATH = path.join(FEATURES, "loader.lua");
const SENTINEL = "REGENERATED by tools/gen-registry.js";
const HAND_BEGIN = "-- >>> HAND-WRITTEN";
const HAND_END = "-- <<< HAND-WRITTEN";

const FORCE = argv.includes("--force");

let existingLoader = null;
try {
    existingLoader = fs.readFileSync(LOADER_PATH, "utf8");
} catch {
    // first run — nothing to preserve
}

if (existingLoader && !FORCE && !existingLoader.includes(SENTINEL)) {
    console.error("");
    console.error("REFUSING to overwrite src/features/loader.lua");
    console.error("");
    console.error("The file exists but does not carry the generator sentinel, so it was");
    console.error("hand-written. Regenerating would destroy it with no warning.");
    console.error("");
    console.error("  - move your content between the HAND-WRITTEN markers and re-run, or");
    console.error("  - re-run with --force to overwrite it deliberately.");
    console.error("");
    process.exit(1);
}

let handBlock =
    "-- Nothing hand-written yet. Anything placed between the HAND-WRITTEN\n" +
    "-- markers survives `node tools/gen-registry.js` verbatim. Everything\n" +
    "-- above them is regenerated from the tree and will be replaced.";

if (existingLoader) {
    const begin = existingLoader.indexOf(HAND_BEGIN);
    const end = existingLoader.indexOf(HAND_END);
    if (begin !== -1 && end !== -1 && end > begin) {
        handBlock = existingLoader.slice(begin + HAND_BEGIN.length, end).trim();
        console.log(`preserving ${handBlock.split("\n").length} line(s) of hand-written loader code`);
    } else if (begin !== -1 || end !== -1) {
        console.log("WARNING: only one HAND-WRITTEN marker found — block NOT preserved");
    }
}

// ── emit ───────────────────────────────────────────────────────────────────
const lines = [];
lines.push(`--[[
    src/features/loader.lua

    REGENERATED by tools/gen-registry.js — do not hand-edit, re-run the tool.

    The OSS release shipped this file as \`-- Omitted. Do this yourself. <3\`.
    It carries two things the rest of the tree cannot run without:

      1. the global \`Feature\` — used 123 times. Every module under
         src/features calls it at load time, e.g.
             return Feature:new("no_shadows", scheduler:add_task(2.5), fn)

      2. aztup.features — read by src/utility/ui/wrapper.lua on every toggle:

             local feature = aztup.features[ID];      -- line 323
             if not feature then return end;          -- line 324
             ...
             if Value then feature:enable() else feature:disable() end;

         With the table empty, all 214 toggles in src/ui/tabs/*.lua set their
         flag and then do nothing.

    ${resolved.length} ids resolved to a module. ${unresolved.length} ids have no module —
    those are option flags consumed by other features, not features themselves.
]]

Feature = require("@src/features/generic_feature");

-- ── globals the stripped loader published ──────────────────────────────────
-- Not features. These were set up by the original loader, and their absence
-- is what makes live errors like "attempt to index nil with 'get_ping'".

-- src/utility/latency.lua was only ever assigned from
-- src/features/auto-parry/auto-parry.lua, and nothing requires that module any
-- more, so bare \`Latency\` was nil. It is read 76 times, including on every
-- animator tick, so it has to exist before any feature loads.
Latency = require("@src/utility/latency");

-- Used 56 times, mostly in the animator handler, and defined nowhere in the
-- release. Silent unless a debug flag is on.
debug_print = function(...)
    if aztup and aztup.flags and aztup.flags.debug then
        print("[pr]", ...);
    end;
end;

local loader = {};

-- id -> module. Generated from the toggle ids in src/ui/tabs/*.lua.
local MODULES = {`);

for (const { id, mod } of resolved) {
    lines.push(`    [${JSON.stringify(id)}] = ${JSON.stringify(mod)},`);
}

lines.push(`};

-- Ids the UI exposes that have no backing module. These are plain flags other
-- features read out of aztup.flags; there is nothing to instantiate.
local OPTION_ONLY = {`);
for (const { id } of unresolved) {
    lines.push(`    ${JSON.stringify(id)},`);
}
lines.push(`};

function loader.initialize()
    local loaded, failed, skipped = 0, 0, 0;

    for id, module in pairs(MODULES) do
        if aztup.features[id] then
            loaded = loaded + 1;
            continue;
        end;

        local ok, feature = pcall(require, module);
        if not ok then
            failed = failed + 1;
            warn(string.format("[features] %s (%s) failed to load: %s", id, module, tostring(feature)));
            continue;
        end;

        if feature == nil then
            -- Side-effect module. src/features/auto-parry/auto-parry.lua is the
            -- example: it returns nil, but requiring it installs the projectile
            -- handlers and publishes getgenv().DefendActionManager, which
            -- animator-handler calls 56 times. It is flag-driven, not a Feature,
            -- so there is nothing to register — loading it is the whole job.
            loaded = loaded + 1;
        elseif type(feature) == "table" and type(feature.disable) == "function" then
            aztup.features[id] = feature;
            loaded = loaded + 1;
        elseif type(feature) == "table" then
            -- A plain table, not a Feature. Registering it would make
            -- init.lua's detach call a disable() that does not exist
            -- ("[detach none] attempt to call missing method 'disable'").
            skipped = skipped + 1;
        elseif type(feature) == "function" then
            -- button-style module: the UI wires these through Func, not features
            aztup.functions = aztup.functions or {};
            aztup.functions[id] = feature;
            loaded = loaded + 1;
        else
            failed = failed + 1;
            warn(string.format("[features] %s (%s) returned %s", id, module, type(feature)));
        end;
    end;

    if skipped > 0 then
        warn(string.format("[features] %d module(s) returned a plain table, not registered", skipped));
    end;

    getgenv().DECAY_registry = { loaded = loaded, failed = failed, modules = MODULES, options = OPTION_ONLY };

    if not aztup.silent_mode and Logger and Logger.log then
        Logger.log(string.format("[features] registered %d, failed %d", loaded, failed));
    end;
end;

function loader.get(id)
    return aztup.features[id];
end;

function loader.is_option(id)
    return table.find(OPTION_ONLY, id) ~= nil;
end;

${HAND_BEGIN}
${handBlock}
${HAND_END}

return loader;
`);

fs.writeFileSync(path.join(FEATURES, "loader.lua"), lines.join("\n"));

console.log(`modules under src/features : ${allModules.length}`);
console.log(`toggle ids found in the UI : ${ids.size}`);
console.log(`resolved to a module       : ${resolved.length}`);
console.log(`option-only (no module)    : ${unresolved.length}`);
if (unresolved.length) {
    console.log("  " + unresolved.map((u) => u.id).join(", "));
}
